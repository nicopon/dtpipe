using System.Data.Common;
using Npgsql;

namespace DtPipe.Coordinator.Server;

/// <summary>
/// The coordinator's state in a PostgreSQL database of its own, which <c>Coordinator:ConnectionString</c> names. The connection is out
/// of the pool and holds a session advisory lock (<see cref="LockKey"/>) for the life of the process; it asks the server to probe its
/// client every few seconds (<c>tcp_keepalives_*</c>), so that the lock of a coordinator whose host vanished is released in about
/// half a minute instead of the system's two hours.
/// </summary>
internal sealed class PostgreSqlDialect(string connectionString) : StoreDialect
{
    /// <summary>The advisory lock of the database: "dtpipeco" in ASCII. A key of the database, so one coordinator per database.</summary>
    public const long LockKey = 0x647470697065636F;

    public override string Name => "PostgreSQL";

    public override string Where => "PostgreSQL, Coordinator:ConnectionString";

    public override bool CanBeLost => true;

    public override string Schema => """
        CREATE TABLE IF NOT EXISTS schema_version (version bigint NOT NULL);
        CREATE TABLE IF NOT EXISTS rights (id integer PRIMARY KEY CHECK (id = 1), doc text NOT NULL, version bigint NOT NULL);
        CREATE TABLE IF NOT EXISTS deployments (pipeline text COLLATE "C" PRIMARY KEY, doc text NOT NULL);
        CREATE TABLE IF NOT EXISTS cursors (pipeline text COLLATE "C" NOT NULL, alias text COLLATE "C" NOT NULL, doc text NOT NULL,
            PRIMARY KEY (pipeline, alias));
        CREATE TABLE IF NOT EXISTS ignored_hosts (subject text COLLATE "C" PRIMARY KEY, until_ms bigint NOT NULL);
        CREATE TABLE IF NOT EXISTS session_keys (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, xml text NOT NULL);
        CREATE TABLE IF NOT EXISTS issuer_keys (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, xml text NOT NULL);
        CREATE TABLE IF NOT EXISTS runs (id text COLLATE "C" PRIMARY KEY, doc text NOT NULL, is_over integer NOT NULL, at_ms bigint NOT NULL);
        CREATE INDEX IF NOT EXISTS runs_by_state ON runs (is_over, at_ms);
        CREATE TABLE IF NOT EXISTS counters (name text COLLATE "C" PRIMARY KEY, value bigint NOT NULL);
        CREATE TABLE IF NOT EXISTS owed (run_id text COLLATE "C" NOT NULL, fragment text COLLATE "C" NOT NULL, node text COLLATE "C" NOT NULL,
            until_ms bigint NOT NULL, PRIMARY KEY (run_id, fragment, node));
        """;

    public override string Upsert(string table, string[] keys, string[] values) => OnConflict(table, keys, values);

    public override string First(string count) => $"LIMIT {count}";

    public override DbConnection? TryConnect()
    {
        NpgsqlConnectionStringBuilder builder;
        try
        {
            builder = new NpgsqlConnectionStringBuilder(connectionString) { Pooling = false, Multiplexing = false };
        }
        catch (Exception ex) when (ex is ArgumentException or FormatException or KeyNotFoundException)
        {
            throw new InvalidOperationException("Coordinator:ConnectionString is not a valid PostgreSQL connection string.");
        }
        var connection = new NpgsqlConnection(builder.ConnectionString);
        try
        {
            connection.Open();
            using var command = connection.CreateCommand();
            command.CommandText = "SET tcp_keepalives_idle = 10; SET tcp_keepalives_interval = 5; SET tcp_keepalives_count = 3;";
            command.ExecuteNonQuery();
            command.CommandText = $"SELECT pg_try_advisory_lock({LockKey})";
            if (command.ExecuteScalar() is true) return connection;
            connection.Dispose();
            return null;
        }
        catch (Exception ex) when (ex is DbException or TimeoutException or OperationCanceledException)
        {
            connection.Dispose();
            throw new InvalidOperationException(
                $"The coordinator could not open its database ({Where}): {(ex is DbException db ? Describe(db) : "timed out")}.");
        }
    }

    public override string Describe(DbException exception) =>
        exception is PostgresException postgres ? $"PostgreSQL error {postgres.SqlState}" : $"PostgreSQL, {exception.GetType().Name}";
}
